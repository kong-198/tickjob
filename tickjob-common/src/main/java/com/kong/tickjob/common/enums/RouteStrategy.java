package com.kong.tickjob.common.enums;

/**
 * 执行器路由策略。
 *
 * <p>调度中心一次触发可能落在多个执行器上（如分片广播），所以路由的产物是
 * <b>一个有序的执行器地址列表</b>，而不是单个地址。触发失败重试时，
 * 调度中心会把已经试过的地址放进 exclude 集合再路由一次，从而天然支持「故障转移」。</p>
 */
public enum RouteStrategy {

    /** 固定选存活列表中最近一次心跳的执行器 */
    FIRST,

    /** 轮询：按任务维度维护游标，同一个任务的多次触发依次落到不同执行器 */
    ROUND,

    /** 随机 */
    RANDOM,

    /**
     * 一致性哈希：以 jobId 为散列键，同一任务始终落在同一个执行器上。
     * 适用于「任务自身有本地状态 / 需要复用连接」的场景，扩容时只迁移少量任务。
     */
    CONSISTENT_HASH,

    /** 故障转移：按最近心跳倒序依次尝试，前面的挂了下一次自动落到后面 */
    FAILOVER,

    /** 分片广播：向所有存活的执行器各触发一次，并下发分片序号与总数 */
    SHARDING_BROADCAST
}
